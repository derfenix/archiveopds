package catalog

// SearchCriteria — фильтры каталога (все заданные поля объединяются по И).
type SearchCriteria struct {
	// Query — свободный текст: все непустые слова должны встречаться (без регистра)
	// в объединении автора, названия, жанра, серии/цикла, номера в серии и др. полей книги.
	Query string

	Author string
	Title  string
	Genre  string
	Series string // подстрока в названии серии/цикла (без регистра)
	Year   int    // 0 — любой год; иначе точное совпадение с полем книги (0 в книге = неизвестно, не совпадает).

	// Page — страница результатов поиска (Limit 0 → DefaultPageSize в навигаторе).
	Page Page
}
